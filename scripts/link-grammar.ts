// Code that can't import outline-core (the mod's hooks load only plugin-local modules; an extension is a folder `ext add`
// copies) gets it bundled beside it. Bundle the shared grammar, never maintain a second parser. `--check`: fail on a stale one.
process.chdir(new URL("..", import.meta.url).pathname);
const BUNDLES = [
  { entry: "packages/claude-mod/scripts/link-grammar-entry.ts", output: "packages/claude-mod/hooks/link-grammar.js" },
  { entry: "packages/outliner/scripts/echonet-grammar-entry.ts", output: "packages/outliner/extensions/echonet/link-grammar.js" },
];
const stale: string[] = [];
for (const { entry, output } of BUNDLES) {
  const result = await Bun.build({ entrypoints: [entry], target: "browser", format: "esm", minify: false });
  if (!result.success) throw new Error(result.logs.join("\n"));
  const text = "// Generated by bun scripts/link-grammar.ts from outline-core.\n" + await result.outputs[0]!.text();
  if (!process.argv.includes("--check")) await Bun.write(output, text);
  else if (!(await Bun.file(output).exists()) || await Bun.file(output).text() !== text) stale.push(output);
}
if (stale.length) throw new Error(`Stale outline-core bundle: ${stale.join(", ")}. Run bun scripts/link-grammar.ts`);
