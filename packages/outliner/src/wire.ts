/*
 * The wire contract (PIE-1375): every action's request and the answer it gets, as one closed record both sides
 * compile against. The outline host checks each answer it writes against `WireAnswers` (server.ts `answered`), and the
 * door's `SocketBoard.request` and `hostRequest` take an action name and return its answer type, so a change on either
 * side that the other doesn't follow fails `bun run check` instead of a door at run time.
 *
 * Types only. The record is closed over `ActionName`: a new action fails the check until it has a row here, as it does
 * in actions.ts. The door checks this file (and what it imports) under its own, stricter settings.
 */
