// Hooks can only load plugin-local modules. Bundle the shared grammar, never maintain a second parser.
process.chdir(new URL("../../..", import.meta.url).pathname);
const result = await Bun.build({
  entrypoints: [new URL("./link-grammar-entry.ts", import.meta.url).pathname],
  target: "browser",
  format: "esm",
  minify: false,
});
if (!result.success) throw new Error(result.logs.join("\n"));
const output = new URL("../hooks/link-grammar.js", import.meta.url);
const text = "// Generated by bun packages/claude-mod/scripts/link-grammar.ts from outline-core.\n" + await result.outputs[0]!.text();
if (process.argv.includes("--check")) {
  if (await Bun.file(output).text() !== text) throw new Error("The mod's grammar is stale: run bun packages/claude-mod/scripts/link-grammar.ts");
} else await Bun.write(output, text);
